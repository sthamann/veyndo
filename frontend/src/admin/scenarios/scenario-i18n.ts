export type ScenarioWord = keyof typeof words;
export function useScenarioText() {
  const { locale } = useLocale();
  const index =
    ({ en: 0, de: 1, fr: 2, es: 3 } as Record<string, number>)[
      locale.slice(0, 2)
    ] ?? 0;
  return (key: ScenarioWord) => words[key][index];
}
